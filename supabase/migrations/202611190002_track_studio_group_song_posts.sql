-- Track successful Studio audio posts sent to the STREET LIFE Stars Telegram group.
create table if not exists public.studio_group_song_posts (
  id bigint generated by default as identity primary key,
  chat_id text not null,
  telegram_message_id bigint not null,
  telegram_user_id bigint not null,
  username text,
  beat_name text not null,
  producer text,
  duration_seconds integer,
  created_at timestamptz not null default now(),
  unique (chat_id, telegram_message_id)
);

create index if not exists studio_group_song_posts_created_at_idx
  on public.studio_group_song_posts (created_at desc);

alter table public.studio_group_song_posts enable row level security;
revoke all on public.studio_group_song_posts from anon, authenticated;
grant all on public.studio_group_song_posts to service_role;
