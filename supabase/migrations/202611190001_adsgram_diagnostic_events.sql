-- Adsgram rewarded-ad diagnostics used by the private STREET LIFE admin panel.
create table if not exists public.adsgram_diagnostic_events (
  id bigint generated by default as identity primary key,
  event_id uuid not null unique,
  session_id uuid not null,
  telegram_id bigint not null,
  block_id text not null default '59485',
  event_type text not null check (event_type in (
    'ad_requested',
    'sdk_loaded',
    'controller_initialized',
    'ad_started',
    'ad_completed',
    'ad_failed',
    'reward_granted'
  )),
  sdk_state text,
  done boolean,
  error boolean,
  description text,
  elapsed_ms integer,
  created_at timestamptz not null default now()
);

create index if not exists adsgram_diagnostic_events_created_at_idx
  on public.adsgram_diagnostic_events (created_at desc);
create index if not exists adsgram_diagnostic_events_telegram_id_idx
  on public.adsgram_diagnostic_events (telegram_id, created_at desc);
create index if not exists adsgram_diagnostic_events_event_type_idx
  on public.adsgram_diagnostic_events (event_type, created_at desc);

alter table public.adsgram_diagnostic_events enable row level security;
revoke all on public.adsgram_diagnostic_events from anon, authenticated;
grant all on public.adsgram_diagnostic_events to service_role;
